for (const line of lines) {
    const p = line.split("\t");
    if (p.length < 7) continue;
    const cc = p[0].trim();
    const bc = p[1].trim();
    const cn = p[2].trim();
    const ts = p[3].trim();
    const rt = p[4].trim();
    const ty = p[5].trim();
    const cap = p[6].trim();

    const talukFull = TALUK_MAP[ts] || ts;
    const routeWhere = TALUK_ROUTE_WHERE[ts] || ts.toUpperCase();
    const capVal = cap && cap !== "0" ? cap : null;
    const capSql = capVal ? `'${capVal}'` : "NULL";
    const rtSql = rt ? `'${rt}'` : "NULL";

    sql += `INSERT IGNORE INTO Clusters (bmcId, bmcCode, routeName, taluk, rtCd, bmcType, capacity, clusterCode, clusterName, memberCode, memberName, createdAt, updatedAt)\n`;
    sql += `SELECT (SELECT id FROM BMCs WHERE bmcCode = '${bc}' AND (isDeleted IS NULL OR isDeleted = 0) LIMIT 1), '${bc}', r.routeName, '${talukFull}', ${rtSql}, '${ty}', ${capSql}, '${cc}', '${cn}', '${cc}', '${cn}', NOW(), NOW()\n`;
    sql += `FROM Routes r WHERE UPPER(r.taluk) = '${routeWhere}' AND (r.isDeleted IS NULL OR r.isDeleted = 0) LIMIT 1;\n\n`;
}

